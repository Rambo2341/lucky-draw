export const locales = ["en", "ar"] as const;
export type Locale = (typeof locales)[number];
export const defaultLocale: Locale = "en";

export function isLocale(value: string): value is Locale {
  return (locales as readonly string[]).includes(value);
}

export const dir = (locale: Locale) => (locale === "ar" ? "rtl" : "ltr");

/** A string available in both languages. */
export type L = { en: string; ar: string };
export const tr = (value: L, locale: Locale) => value[locale];

/** Prefixes an internal path with the locale: href("en", "/properties") → "/en/properties". */
export const href = (locale: Locale, path = "") => `/${locale}${path === "/" ? "" : path}`;

